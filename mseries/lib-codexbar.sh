# shellcheck shell=bash
# Shared CodexBar port payload. Sourced by install-codexbar.sh, install-codexbar-wingpanel.sh and
# deploy-codexbar.sh so the helper set cannot drift between them. enhance.sh copies the same files
# into the image; test-codexbar-deploy.py checks that list and every helper's local imports against this one.

# Python helpers installed into ~/.local/lib/codexbar-cli (modules use _, executables use -).
CODEXBAR_HELPERS=(
  codexbar_cache.py
  codexbar_tokens.py
  codexbar_history.py
  codexbar_claude_history.py
  codexbar_claude_handoff.py
  codexbar-sessions.py
  codexbar-accounts.py
  codexbar-claude.py
  codexbar-opencode-local.py
  codexbar-opencode-login.py
  codexbar-wingpanel-watch.py
)

# Provider marks installed as mseries-codexbar-<name>-symbolic.svg (read by the sourcing scripts).
# shellcheck disable=SC2034
CODEXBAR_MARKS=(openai claude opencode grok)

# codexbar_install_helpers REPO: install every helper; executables 0755, imported modules 0644.
codexbar_install_helpers() {
  local repo=$1 lib="$HOME/.local/lib/codexbar-cli" helper mode
  mkdir -p "$lib"
  for helper in "${CODEXBAR_HELPERS[@]}"; do
    mode=0755
    [[ $helper == *_* && $helper != *-* ]] && mode=0644
    install -m "$mode" "$repo/mseries/$helper" "$lib/$helper"
  done
  codexbar_install_cli_compat
}

# codexbar_cli_needs_libxml2 BINARY: true when the CLI binary links libxml2.so.2.
codexbar_cli_needs_libxml2() {
  LC_ALL=C ldd "$1" 2>/dev/null | grep -q 'libxml2\.so\.2'
}

# codexbar_install_cli_compat: upstream v0.78.0's CLI links libxml2.so.2, but
# libxml2 >= 2.14 renamed the soname (libxml2.so.16 on this base), so the CLI
# cannot load. Resolve the old soname from a compat directory and route
# codexbar-upstream through a wrapper that points the loader there. The wrapper
# is a no-op when the system provides libxml2.so.2 (an older base). Upstream
# v0.79.0 and later no longer link libxml2; for them the shim removes itself.
# Idempotent: the real binary's name is remembered in codexbar-upstream.real.
codexbar_install_cli_compat() {
  local lib="$HOME/.local/lib/codexbar-cli" soname real base current
  [[ -e $lib/codexbar-upstream || -L $lib/codexbar-upstream ]] || return 0
  if [[ -f $lib/codexbar-upstream && ! -L $lib/codexbar-upstream \
        && $(head -c 2 "$lib/codexbar-upstream") == '#!' ]]; then
    # Our wrapper: the binary it runs is the current CLI.
    current=$lib/$(cat "$lib/codexbar-upstream.real" 2>/dev/null)
  else
    # An install moved upstream's codexbar (a symlink to CodexBarCLI, or a plain binary)
    # over the wrapper. It is current; a remembered name may point at the previous version.
    current=$(readlink -f "$lib/codexbar-upstream")
    [[ $current == "$lib/codexbar-upstream.bin" ]] || rm -f "$lib/codexbar-upstream.bin"
    rm -f "$lib/codexbar-upstream.real"
  fi
  if [[ -f $current ]] && ! codexbar_cli_needs_libxml2 "$current"; then
    # Upstream v0.79.0+ does not link libxml2: point codexbar-upstream straight at the
    # binary (rename, so callers never find it missing) and drop the shim.
    if [[ $current != "$(readlink -f "$lib/codexbar-upstream")" ]]; then
      ln -sfn "$(basename "$current")" "$lib/codexbar-upstream.new"
      mv -f "$lib/codexbar-upstream.new" "$lib/codexbar-upstream"
    fi
    rm -f "$lib/codexbar-upstream.real"
    rm -rf "$lib/compat"
    return 0
  fi
  if ldconfig -p | awk '{print $1}' | grep -qx libxml2.so.2; then
    return 0
  fi
  soname=$(ldconfig -p | awk '$1 ~ /^libxml2\.so\./ {print $1}' | sort -V | tail -1)
  [[ -n $soname ]] || { echo 'codexbar: no libxml2 found for the CLI compat shim' >&2; return 1; }
  if [[ -f $lib/codexbar-upstream.real ]]; then
    base=$(cat "$lib/codexbar-upstream.real")
  else
    if [[ -L $lib/codexbar-upstream ]]; then
      real=$(readlink -f "$lib/codexbar-upstream")
    else
      mv -f "$lib/codexbar-upstream" "$lib/codexbar-upstream.bin"
      real="$lib/codexbar-upstream.bin"
    fi
    base=$(basename "$real")
    printf '%s\n' "$base" > "$lib/codexbar-upstream.real"
  fi
  mkdir -p "$lib/compat"
  ln -sfn "$(ldconfig -p | awk -v s="$soname" '$1 == s {print $NF; exit}')" "$lib/compat/libxml2.so.2"
  # Remove the path first: it is a symlink to the real binary, and a redirect
  # would follow it and truncate the binary instead of replacing the link.
  rm -f "$lib/codexbar-upstream"
  cat > "$lib/codexbar-upstream" <<EOF
#!/bin/sh
# Generated by codexbar_install_cli_compat: the upstream CLI links libxml2.so.2
# and this base provides $soname. Remove when upstream rebuilds against
# libxml2 >= 2.14 or the base regains libxml2.so.2.
dir=\$(CDPATH= cd -- "\$(dirname -- "\$0")" && pwd)
LD_LIBRARY_PATH="\$dir/compat\${LD_LIBRARY_PATH:+:\$LD_LIBRARY_PATH}"
export LD_LIBRARY_PATH
exec "\$dir/$base" "\$@"
EOF
  chmod 0755 "$lib/codexbar-upstream"
}

# codexbar_install_wrapper REPO: replace ~/.local/bin/codexbar atomically so the panel never finds it missing.
codexbar_install_wrapper() {
  local repo=$1
  mkdir -p "$HOME/.local/bin"
  install -m 0755 "$repo/mseries/codexbar-opencode-wrapper.py" "$HOME/.local/bin/codexbar.new"
  mv -f "$HOME/.local/bin/codexbar.new" "$HOME/.local/bin/codexbar"
}
