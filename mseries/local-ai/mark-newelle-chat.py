#!/usr/bin/env python3
"""Mark Newelle as a Smart Reply chat app (design: mseries/SMART-REPLY-DESIGN.md).

Newelle is a Flatpak, so its desktop entry is not ours to edit. This writes a user-level copy of the exported entry with
`X-MSeries-Chat=true` added, which the Smart Reply marker lookup finds first. Idempotent; run it again after a Flatpak
update to pick up a changed entry. `--remove` deletes only a copy this script wrote.
"""
import argparse
import os
import sys
from pathlib import Path

APP_ID = 'io.github.qwersyk.Newelle'
MARK = 'X-MSeries-Chat=true'
GENERATED = '# Generated by mseries/local-ai/mark-newelle-chat.py; safe to delete.'


def data_home():
    return Path(os.environ.get('XDG_DATA_HOME') or Path.home() / '.local/share')


def exported_entry():
    candidates = [data_home() / 'flatpak/exports/share/applications' / f'{APP_ID}.desktop',
                  Path('/var/lib/flatpak/exports/share/applications') / f'{APP_ID}.desktop']
    return next((path for path in candidates if path.is_file()), None)


def marked(text):
    """The entry text with the marker added to the [Desktop Entry] group, or unchanged if already marked."""
    if any(line.strip() == MARK for line in text.splitlines()):
        return text
    out, inserted = [], False
    for line in text.splitlines():
        if line.startswith('[') and out and not inserted and out[0].strip() == '[Desktop Entry]':
            while out and not out[-1].strip():
                out.pop()
            out.append(MARK)
            out.append('')
            inserted = True
        out.append(line)
    if not inserted:
        while out and not out[-1].strip():
            out.pop()
        out.append(MARK)
    return '\n'.join(out) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    parser.add_argument('--remove', action='store_true')
    args = parser.parse_args()
    target = data_home() / 'applications' / f'{APP_ID}.desktop'
    if args.remove:
        if target.is_file() and GENERATED in target.read_text():
            target.unlink()
            print(f'Removed {target}')
        return 0
    source = exported_entry()
    if source is None:
        print(f'{APP_ID} is not installed as a Flatpak; nothing to mark.', file=sys.stderr)
        return 1
    text = source.read_text()
    if GENERATED not in text:
        head, _, rest = text.partition('\n')
        text = f'{head}\n{GENERATED}\n{rest}' if head.strip() == '[Desktop Entry]' else text
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(marked(text))
    print(f'Marked {APP_ID} as a chat app: {target}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
